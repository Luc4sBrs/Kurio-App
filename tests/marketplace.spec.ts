import { expect, test, type Page } from '@playwright/test'

async function resetDemo(page: Page) {
  await page.goto('/')
  await page.waitForFunction(() => document.documentElement.dataset.mockReady === 'true')
  await page.getByRole('heading', { name: /seja dono/i }).waitFor()
  await page.evaluate(async () => {
    await fetch('/api/scenarios/reset', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ scenario: 'standard' }) })
    localStorage.clear()
    sessionStorage.clear()
  })
  await page.reload()
  await page.waitForFunction(() => document.documentElement.dataset.mockReady === 'true')
  await page.getByRole('heading', { name: /seja dono/i }).waitFor()
  await page.getByRole('link', { name: 'Emerald Ape #42', exact: true }).waitFor()
}

