test('catalog search, combined filters, sorting, pagination, and browser history', async ({ page }) => {
  if (page.viewportSize()!.width < 620) await page.getByRole('button', { name: 'Abrir busca' }).click()
  await page.getByRole('searchbox', { name: 'Buscar no marketplace' }).fill('moss')
  await page.getByRole('searchbox', { name: 'Buscar no marketplace' }).press('Enter')
  await expect(page).toHaveURL(/q=moss/)
  await expect(page.getByRole('link', { name: 'Moss Captain #05', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'PFP' }).click()
  await expect(page).toHaveURL(/category=PFP/)
  const mobileLayout = page.viewportSize()!.width <= 850
  const sortControl = mobileLayout ? page.locator('.sort-select-wrap select') : page.locator('.catalog-sidebar select')
  await sortControl.selectOption('price-desc')
  await expect(page).toHaveURL(/sort=price-desc/)
  if (mobileLayout) await page.getByRole('button', { name: /Filtros/ }).click()
  const minPriceInput = mobileLayout ? page.locator('.filter-panel [aria-label="Preço mínimo"]') : page.locator('.catalog-sidebar [aria-label="Preço mínimo"]')
  await minPriceInput.fill('0.5')
  await expect.poll(() => new URL(page.url()).searchParams.get('minPrice')).toBe('"0.5"')
  await page.goBack()
  await expect.poll(() => new URL(page.url()).searchParams.has('minPrice')).toBe(false)
  await page.goto('/?page=1')
  await expect(page.getByRole('button', { name: 'Próxima página' })).toBeVisible()
  await page.getByRole('button', { name: 'Próxima página' }).click()
  await expect(page).toHaveURL(/page=2/)
})

