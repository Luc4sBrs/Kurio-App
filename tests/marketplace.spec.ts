test('slow requests show skeletons and retry recovers from a catalog outage', async ({ page }) => {
  await page.getByRole('button', { name: /DEMO/ }).click()
  await page.getByLabel('Cenário de rede').selectOption('slow')
  await expect(page.getByText(/Cenário de demonstração: Rede lenta/i)).toBeVisible()
  await page.reload()
  await expect(page.locator('.skeleton-card').first()).toBeVisible()
  await expect(page.getByRole('link', { name: 'Emerald Ape #42', exact: true })).toBeVisible({ timeout: 7_000 })

  await page.getByRole('button', { name: /DEMO/ }).click()
  await page.getByLabel('Cenário de rede').selectOption('http-error')
  await expect(page.getByText(/Cenário de demonstração: Falha HTTP 503/i)).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'O catálogo não carregou' })).toBeVisible()
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  // a nova tentativa mostra o skeleton e repete a requisição (retry: 1); só depois o erro volta
  await expect(page.locator('.skeleton-card').first()).toBeVisible()
  await expect(page.getByRole('heading', { name: 'O catálogo não carregou' })).toBeVisible()
  await page.getByRole('button', { name: /DEMO/ }).click()
  await page.getByLabel('Cenário de rede').selectOption('standard')
  await expect(page.getByText(/Cenário de demonstração: Padrão/i)).toBeVisible()
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  await expect(page.getByRole('link', { name: 'Emerald Ape #42', exact: true })).toBeVisible()
})

